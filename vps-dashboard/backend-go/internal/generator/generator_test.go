func TestDockerRunBasic(t *testing.T) {
	got, err := DockerRun(DockerRunOpts{
		Name:     "webapp",
		Image:    "node:20-alpine",
		Detached: true,
		Restart:  "unless-stopped",
		Ports: []PortMapping{
			{Host: 8080, Container: 80, Protocol: "tcp"},
		},
		Volumes: []VolumeMapping{
			{Host: "/data", Container: "/var/lib/app", Mode: "rw"},
		},
		Env: []EnvVar{
			{Key: "NODE_ENV", Value: "production"},
		},
		Command: "node server.js",
	})
	if err != nil {
		t.Fatalf("DockerRun: %v", err)
	}

	wants := []string{
		"docker run -d",
		"--name 'webapp'",
		"--restart unless-stopped",
		"-p '8080:80/tcp'",
		"-v '/data:/var/lib/app:rw'",
		"-e 'NODE_ENV=production'",
		"'node:20-alpine'",
		"'node server.js'",
	}
	for _, w := range wants {
		if !strings.Contains(got, w) {
			t.Errorf("expected output to contain %q\ngot:\n%s", w, got)
		}
	}
}

func TestDockerRunValidation(t *testing.T) {
	cases := []struct {
		name string
		opts DockerRunOpts
		want string
	}{
		{
			name: "missing name",
			opts: DockerRunOpts{Image: "alpine"},
			want: "name: required",
		},
		{
			name: "missing image",
			opts: DockerRunOpts{Name: "x"},
			want: "image: required",
		},
		{
			name: "bad restart",
			opts: DockerRunOpts{Name: "x", Image: "alpine", Restart: "loop"},
			want: "restart:",
		},
		{
			name: "bad port",
			opts: DockerRunOpts{Name: "x", Image: "alpine",
				Ports: []PortMapping{{Host: 0, Container: 80}}},
			want: "ports[0].host",
		},
		{
			name: "bad protocol",
			opts: DockerRunOpts{Name: "x", Image: "alpine",
				Ports: []PortMapping{{Host: 80, Container: 80, Protocol: "icmp"}}},
			want: "protocol",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := DockerRun(tc.opts)
			if err == nil {
				t.Fatalf("expected error containing %q", tc.want)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error %q should contain %q", err.Error(), tc.want)
			}
		})
	}
}

