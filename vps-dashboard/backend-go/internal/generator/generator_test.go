func TestNginxReverseProxyPlain(t *testing.T) {
	got, err := NginxReverseProxy(NginxOpts{
		Domain:       "x.test",
		UpstreamHost: "127.0.0.1",
		UpstreamPort: 3001,
	})
	if err != nil {
		t.Fatalf("NginxReverseProxy: %v", err)
	}
	for _, w := range []string{
		"server {",
		"listen 80;",
		"server_name x.test;",
		"proxy_pass http://127.0.0.1:3001;",
		"X-Forwarded-For $proxy_add_x_forwarded_for;",
	} {
		if !strings.Contains(got, w) {
			t.Errorf("expected output to contain %q\ngot:\n%s", w, got)
		}
	}
	if strings.Contains(got, "listen 443") {
		t.Errorf("plain proxy should not contain `listen 443`\ngot:\n%s", got)
	}
}

func TestNginxReverseProxySSL(t *testing.T) {
	got, err := NginxReverseProxy(NginxOpts{
		Domain:          "x.test",
		UpstreamHost:    "127.0.0.1",
		UpstreamPort:    3001,
		EnableSSL:       true,
		SSLCertPath:     "/etc/letsencrypt/live/x.test/fullchain.pem",
		SSLKeyPath:      "/etc/letsencrypt/live/x.test/privkey.pem",
		EnableWebsocket: true,
	})
	if err != nil {
		t.Fatalf("NginxReverseProxy ssl: %v", err)
	}
	for _, w := range []string{
		"listen 80;",
		"return 301 https://$host$request_uri;",
		"listen 443 ssl;",
		"ssl_certificate /etc/letsencrypt/live/x.test/fullchain.pem;",
		"ssl_certificate_key /etc/letsencrypt/live/x.test/privkey.pem;",
		"proxy_set_header Upgrade $http_upgrade;",
	} {
		if !strings.Contains(got, w) {
			t.Errorf("expected output to contain %q\ngot:\n%s", w, got)
		}
	}
}

