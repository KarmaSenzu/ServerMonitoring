func TestGeneratorDockerSuccess(t *testing.T) {
	f := newTestFixture(t)
	tok := loginToken(t, f)

	rec := f.do(t, http.MethodPost, "/generator/docker", map[string]any{
		"name":     "app",
		"image":    "node:20",
		"detached": true,
		"restart":  "unless-stopped",
		"ports": []map[string]any{
			{"host": 8080, "container": 80, "protocol": "tcp"},
		},
	}, map[string]string{
		"Authorization": "Bearer " + tok,
	})

	if rec.Code != http.StatusOK {
		t.Fatalf("status: got %d want %d body=%s", rec.Code, http.StatusOK, rec.Body.String())
	}
	body := parseJSON(t, rec)
	cmd, _ := body["command"].(string)
	if !strings.Contains(cmd, "--name 'app'") {
		t.Errorf("command should contain --name 'app', got: %s", cmd)
	}
	if !strings.Contains(cmd, "'node:20'") {
		t.Errorf("command should contain 'node:20', got: %s", cmd)
	}
}

