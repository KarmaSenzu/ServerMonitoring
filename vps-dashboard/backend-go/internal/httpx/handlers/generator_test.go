func TestGeneratorTunnelsEmpty(t *testing.T) {
	// On dev mac /etc/cloudflared rarely exists; the route must respond 200
	// with an empty list rather than crashing.
	f := newTestFixture(t)
	tok := loginToken(t, f)
	rec := f.do(t, http.MethodGet, "/system/tunnels", nil, map[string]string{
		"Authorization": "Bearer " + tok,
	})
	if rec.Code != http.StatusOK {
		t.Fatalf("status: got %d want %d body=%s", rec.Code, http.StatusOK, rec.Body.String())
	}
	body := parseJSON(t, rec)
	if _, ok := body["data"]; !ok {
		t.Errorf("expected `data` key in body, got %v", body)
	}
}
